type IconProps = SVGProps<SVGSVGElement> & { size?: string | number };

// Keep the hit area on the control, the outer icon box at 24px, and the
// 24-unit Reicon artwork at 18px (2 SVG units become 1.5 CSS pixels).
function icon(Artwork: ComponentType<IconProps>) {
  return memo(forwardRef<SVGSVGElement, IconProps>(function ConsoleIcon(
    { size: _size, strokeWidth: _stroke, "aria-hidden": hidden, ...props }, ref,
  ) {
    const named = props["aria-label"] || props["aria-labelledby"];
    return <svg ref={ref} data-console-icon="" width={24} height={24} viewBox="0 0 24 24" focusable="false"
      aria-hidden={hidden ?? (!named || undefined)} role={named ? "img" : undefined} {...props}>
      <Artwork aria-hidden="true" size={18} x={3} y={3} strokeWidth={2} />
    </svg>;
  }));
}

